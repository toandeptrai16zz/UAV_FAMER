#!/bin/sh
set -eu
cd "$(dirname "$0")/.."
test_bin=$(mktemp)
trap 'rm -f "$test_bin"' EXIT
# R5 captive experiment includes a one-shot ARM safety interlock.
cc -std=c11 -O2 -g -Wall -Wextra -Wno-unused-function -Wno-unused-variable -Wno-unused-parameter \
  -fsanitize=undefined -fno-sanitize-recover=all -Itests/mocks -ICore/Inc \
  tests/test_flight.c Core/Src/flight_pid.c Core/Src/rc_input.c Core/Src/uav_rate_blackbox.c Core/Src/uav_imu_raw.c Core/Src/uav_cage_guard.c -lm -o "$test_bin"
"$test_bin"
# Also compile a locked R4-style fallback where motor commands remain disabled.
cc -std=c11 -O2 -g -Wall -Wextra -Wno-unused-variable -Wno-unused-parameter \
  -DUAV_CAGE_TEST_ARM_ENABLE=0 -DUAV_YAW_DIAGNOSTIC_ARM_LOCK=1 -fsanitize=undefined -fno-sanitize-recover=all \
  -Itests/mocks -ICore/Inc tests/test_flight.c Core/Src/flight_pid.c \
  Core/Src/rc_input.c Core/Src/uav_rate_blackbox.c Core/Src/uav_imu_raw.c Core/Src/uav_cage_guard.c -lm -o "$test_bin"
"$test_bin"
cage_test_bin=$(mktemp)
trap 'rm -f "$test_bin" "$cage_test_bin"' EXIT
cc -std=c11 -O2 -g -Wall -Wextra -Werror -fsanitize=undefined -fno-sanitize-recover=all \
  -ICore/Inc tests/test_cage_guard.c Core/Src/uav_cage_guard.c -lm -o "$cage_test_bin"
"$cage_test_bin"
python3 tests/test_protocol.py

config_test_bin=$(mktemp)
trap 'rm -f "$test_bin" "$config_test_bin"' EXIT
cc -std=c11 -O2 -g -Wall -Wextra -Werror -fsanitize=undefined -fno-sanitize-recover=all \
  -ICore/Inc tests/test_config_gate.c -o "$config_test_bin"
"$config_test_bin"

blackbox_test_bin=$(mktemp)
trap 'rm -f "$test_bin" "$config_test_bin" "$blackbox_test_bin"' EXIT
cc -std=c11 -O2 -g -Wall -Wextra -Werror -fsanitize=undefined -fno-sanitize-recover=all \
  -ICore/Inc tests/test_blackbox.c Core/Src/uav_rate_blackbox.c -o "$blackbox_test_bin"
"$blackbox_test_bin"
python3 tests/test_blackbox_protocol.py
python3 -m py_compile Telemetry/UAV_GroundStation_Realtime_Charts/*.py
wire_bin=$(mktemp)
wire_data=$(mktemp)
trap 'rm -f "$test_bin" "$config_test_bin" "$blackbox_test_bin" "$wire_bin" "$wire_data"' EXIT
cc -std=c11 -O2 -Wall -Wextra -Werror -Itests/mocks -ICore/Inc \
  tests/test_wire_blackbox.c Core/Src/uav_telemetry.c -o "$wire_bin"
"$wire_bin" > "$wire_data"
python3 tests/test_wire_blackbox.py "$wire_data"
python3 tests/test_dashboard_blackbox_integration.py

imu_raw_bin=$(mktemp)
imu_wire_bin=$(mktemp)
imu_wire_data=$(mktemp)
trap 'rm -f "$test_bin" "$config_test_bin" "$blackbox_test_bin" "$wire_bin" "$wire_data" "$imu_raw_bin" "$imu_wire_bin" "$imu_wire_data"' EXIT
cc -std=c11 -O2 -Wall -Wextra -Werror -ICore/Inc tests/test_imu_raw.c Core/Src/uav_imu_raw.c -o "$imu_raw_bin"
"$imu_raw_bin"
cc -std=c11 -O2 -Wall -Wextra -Werror -Itests/mock_hal -ICore/Inc \
  tests/test_wire_imu.c Core/Src/uav_telemetry.c -o "$imu_wire_bin"
"$imu_wire_bin" "$imu_wire_data"
# Test raw packet decoder with C-generated bytes, not an independent Python encoder.
PYTHONPATH=Telemetry/UAV_GroundStation_Realtime_Charts python3 - "$imu_wire_data" <<'PYTEST'
import sys
from uav_imu_raw_decoder import decode_imu
r=decode_imu(open(sys.argv[1],'rb').read())
assert r and r['gyro_y_raw']==-40 and r['capture_kind']=='MOTOR_STOP'
print('PASS IMU type3 C packet/CRC/Python decoder')
PYTEST
PYTHONPATH=Telemetry/UAV_GroundStation_Realtime_Charts python3 tests/test_dashboard_imu.py

# R5.6: compile ACTUAL config source with simulated STM32 dual-bank Flash.
# Verify UART control replies/CRC, 2s static gate, capture limits, PID record
# compatibility and interrupted Flash write rollback.
level_test_bin=$(mktemp)
trap 'rm -f "$test_bin" "$config_test_bin" "$blackbox_test_bin" "$wire_bin" "$wire_data" "$imu_raw_bin" "$imu_wire_bin" "$imu_wire_data" "$level_test_bin"' EXIT
cc -std=c11 -O2 -Wall -Wextra -Werror -Wno-unused-function -Wno-unused-parameter \
 -fsanitize=undefined -fno-sanitize-recover=all -Itests/config_mock -ICore/Inc \
 tests/test_level_reference.c Core/Src/flight_pid.c -lm -o "$level_test_bin"
"$level_test_bin"
